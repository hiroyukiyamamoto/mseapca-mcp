immune <- search_sets(source="ImmuneCellMetabolomics",limit=100L)
stopifnot(immune$ok, immune$total==583L)
ids <- list("IMMUNE_ST001283_AN002127_C180_UP", "IMMUNE_ST001283_AN002127_C180_DOWN")
sets <- get_sets(ids,identifier="name",max_members=500L)
stopifnot(sets$ok,length(sets$sets)==2L,
  all(c("glucose-6-phosphate","glutamine","cystine") %in% unlist(sets$sets[[1]]$members)),
  all(c("aspartic acid","myo-inositol") %in% unlist(sets$sets[[2]]$members)))
source("R/analysis.R")
detected <- as.list(unique(unlist(lapply(sets$sets,function(s)s$members))))
up <- analyze_ora(list("glucose-6-phosphate","glutamine","cystine"),detected,ids)
down <- analyze_ora(list("aspartic acid","myo-inositol"),detected,ids)
stopifnot(up$ok,down$ok,length(up$results)==2L,length(down$results)==2L)
up_counts <- setNames(vapply(up$results,function(r)r$overlap_count,integer(1)),vapply(up$results,function(r)r$set_id,character(1)))
down_counts <- setNames(vapply(down$results,function(r)r$overlap_count,integer(1)),vapply(down$results,function(r)r$set_id,character(1)))
stopifnot(up_counts[[ids[[1]]]]==3L,up_counts[[ids[[2]]]]==0L,
  down_counts[[ids[[1]]]]==0L,down_counts[[ids[[2]]]]==2L)
cat("Immune set retrieval and separate UP/DOWN ORA passed.\n")
